def _run_models(conn: sqlite3.Connection) -> Dict[str, str]:
    """{run_id: model} from the runs table; empty when there is none."""
    try:
        return {str(r[0]): str(r[1] or "") for r in conn.execute("SELECT run_id, model FROM runs").fetchall() if r[0]}
    except sqlite3.Error:
        return {}


def _export_runs(conn: sqlite3.Connection) -> List[Dict[str, Any]]:
    try:
        rows = conn.execute("SELECT run_id, model, started FROM runs ORDER BY started ASC, run_id ASC").fetchall()
    except sqlite3.Error:
        return []
    return [{"run_id": _scrub(r[0], MAX_SHORT_CHARS), "model": _scrub(r[1], MAX_SHORT_CHARS),
             "started": _scrub(r[2], MAX_SHORT_CHARS)} for r in rows if r[0]]


def _export_findings(conn: sqlite3.Connection, repo_root: Optional[str]) -> List[Dict[str, Any]]:
    """Latest row per lineage (or per signature, or per location+title when the
    row predates both), as the export's view of each finding. Each carries
    the model of the run that wrote it, when the database knows it."""
    models = _run_models(conn)
    try:
        rows = conn.execute("SELECT * FROM findings ORDER BY id ASC").fetchall()
    except sqlite3.Error:
        return []
    latest: Dict[Tuple[str, str], sqlite3.Row] = {}
    for row in rows:
        r = dict(row)
        if r.get("lineage_id"):
            key = ("lineage", str(r["lineage_id"]))
        elif r.get("signature"):
            key = ("signature", str(r["signature"]))
        else:
            key = ("loc", f"{r.get('filepath')}|{r.get('title')}|{r.get('line_numbers')}")
        latest[key] = row  # later rows win: ORDER BY id ASC
    out: List[Dict[str, Any]] = []
    for row in latest.values():
        r = dict(row)
        rec: Dict[str, Any] = {}
        for f in FINDING_FIELDS:
            v = models.get(str(r.get("run_id") or ""), "") if f == "model" else r.get(f)
            if f == "filepath":
                v = str(v or "")
                if os.path.isabs(v):
                    v = _relativize(v, repo_root) or v
                v = _scrub(v, 1024)
            elif f in ("line_numbers", "code_paths"):
                v = _parse_list(v)
                if f == "line_numbers":
                    v = [int(x) for x in v if isinstance(x, int) and not isinstance(x, bool) and x > 0]
                else:
                    v = [_scrub(x, 1024) for x in v if isinstance(x, str)]
            elif f in _TEXT_FIELDS:
                v = _scrub(v)
            elif isinstance(v, str):
                v = _scrub(v, MAX_SHORT_CHARS)
            rec[f] = v
        out.append(rec)
    out.sort(key=lambda r: (str(r.get("filepath") or ""), str(r.get("lineage_id") or ""),
                            str(r.get("title") or ""), str(r.get("signature") or "")))
    return out


def _export_learnings(conn: sqlite3.Connection) -> List[Dict[str, Any]]:
    models = _run_models(conn)
    try:
        rows = conn.execute(
            "SELECT run_id, timestamp, category, learning, tags FROM learnings ORDER BY id ASC"
        ).fetchall()
    except sqlite3.Error:
        return []
    seen: Dict[Tuple[str, str], Dict[str, Any]] = {}
    for row in rows:
        r = dict(row)
        cat = _scrub(r.get("category"), MAX_SHORT_CHARS)
        text = _scrub(r.get("learning"))
        if not text:
            continue
        seen[(cat, text)] = {
            "category": cat,
            "learning": text,
            "tags": [_scrub(t, MAX_SHORT_CHARS) for t in _parse_list(r.get("tags")) if isinstance(t, str)],
            "run_id": _scrub(r.get("run_id"), MAX_SHORT_CHARS),
            "model": models.get(str(r.get("run_id") or ""), ""),
            "timestamp": _scrub(r.get("timestamp"), MAX_SHORT_CHARS),
        }
    return sorted(seen.values(), key=lambda x: (x["category"], x["learning"]))


def _latest_artifact(conn: sqlite3.Connection, artifact_type: str = "",
                     filepaths: Iterable[str] = ()) -> Optional[str]:
    clauses, params = [], []
    if artifact_type:
        clauses.append("artifact_type = ?")
        params.append(artifact_type)
    fps = list(filepaths)
    if fps:
        clauses.append("filepath IN (%s)" % ",".join("?" * len(fps)))
        params.extend(fps)
    if not clauses:
        return None
    try:
        row = conn.execute(
            "SELECT content FROM campaign_artifacts WHERE " + " AND ".join(clauses)
            + " ORDER BY id DESC LIMIT 1", params).fetchone()
    except sqlite3.Error:
        return None
    return str(row[0]) if row and row[0] is not None else None


def _export_coverage(conn: sqlite3.Connection, repo_root: Optional[str]) -> Dict[str, Any]:
    """Coverage as repository-relative paths: the ledger's examined areas per
    run, and every target a completed campaign recorded spend for -- per
    model, so a path one model covered is still open for another."""
    from core.memory import COVERAGE_ARTIFACT_TYPE

    models = _run_models(conn)
    runs: List[Dict[str, Any]] = []
    try:
        rows = conn.execute(
            "SELECT content FROM campaign_artifacts WHERE artifact_type LIKE ? ORDER BY id ASC",
            (COVERAGE_ARTIFACT_TYPE + ":%",)).fetchall()
    except sqlite3.Error:
        rows = []
    seen_runs = set()
    for (content,) in rows:
        try:
            parsed = json.loads(content or "{}")
        except ValueError:
            continue
        for entry in (parsed.get("runs") or []) if isinstance(parsed, dict) else []:
            if not isinstance(entry, dict):
                continue
            run_id = _scrub(entry.get("run_id"), MAX_SHORT_CHARS)
            examined = sorted({_relativize(str(p), repo_root) for p in (entry.get("examined") or [])
                               if isinstance(p, str)} - {""})
            key = (run_id, tuple(examined))
            if not examined or key in seen_runs:
                continue
            seen_runs.add(key)
            runs.append({"run_id": run_id,
                         "model": models.get(run_id, ""),
                         "snapshot_id": _scrub(entry.get("snapshot_id"), MAX_SHORT_CHARS),
                         "examined": examined})
    scanned: Dict[str, Dict[str, Any]] = {}
    # The ledger grew `harness_fingerprint` after it first shipped; a database
    # last written by an older Mantis has no such column and must still export.
    from core.cost import _row_failed, has_fingerprint_column

    try:
        fp_col = "harness_fingerprint" if has_fingerprint_column(conn) else "NULL AS harness_fingerprint"
        spend = conn.execute(
            f"SELECT target, scan_mode, run_id, tokens, metadata_json, {fp_col} FROM campaign_spend ORDER BY id ASC").fetchall()
    except sqlite3.Error:
        spend = []
    for row in spend:
        r = dict(row)
        if _row_failed(r.get("metadata_json")):
            continue
        rel = _relativize(str(r.get("target") or ""), repo_root)
        if not rel:
            continue
        run_id = _scrub(r.get("run_id"), MAX_SHORT_CHARS)
        model = models.get(run_id, "")
        scanned[(rel, model)] = {"path": rel, "scan_mode": _scrub(r.get("scan_mode"), MAX_SHORT_CHARS),
                                 "last_run_id": run_id, "model": model,
                                 "harness_fingerprint": _scrub(r.get("harness_fingerprint"), MAX_SHORT_CHARS)}
    # What content each covered file was examined as (core.cost
    # .coverage_files), so an importing checkout can tell a file edited
    # since from one that merely moved machines. mtime is not exported: it
    # is this machine's; the importer hashes once instead.
    files: List[Dict[str, Any]] = []
    try:
        from core.cost import has_coverage_files_table

        if has_coverage_files_table(conn):
            latest: Dict[tuple, Dict[str, Any]] = {}
            for row in conn.execute(
                    "SELECT path, run_id, content_hash, size FROM coverage_files ORDER BY id ASC").fetchall():
                r = dict(row)
                rel = _relativize(str(r.get("path") or ""), repo_root)
                run_id = _scrub(r.get("run_id"), MAX_SHORT_CHARS)
                digest = _scrub(r.get("content_hash"), MAX_SHORT_CHARS)
                if not rel or not digest:
                    continue
                latest[(rel, models.get(run_id, ""))] = {
                    "path": rel, "run_id": run_id, "model": models.get(run_id, ""),
                    "content_hash": digest,
                    "size": int(r["size"]) if r.get("size") is not None else None}
            files = [latest[k] for k in sorted(latest)]
    except sqlite3.Error:
        files = []
    return {"schema_version": SCHEMA_VERSION, "runs": runs,
            "scanned": [scanned[k] for k in sorted(scanned)], "files": files}


def _git_head(repo_root: Optional[str]) -> str:
    """The commit the repository is at, or '' when it is not a git checkout."""
    if not repo_root:
        return ""
    try:
        import subprocess

        out = subprocess.run(["git", "-C", str(repo_root), "rev-parse", "--verify", "--quiet",
                              "--end-of-options", "HEAD"], capture_output=True, text=True, timeout=30)
        sha = out.stdout.strip()
        return sha if out.returncode == 0 and re.fullmatch(r"[0-9a-f]{7,64}", sha) else ""
    except Exception:
        return ""


def read_head(in_dir: str) -> str:
    """The commit a knowledge export says it reflects (manifest `head`), or ''."""
    raw = _read_bounded(Path(in_dir) / MANIFEST, 1 << 20)
    if raw is None:
        return ""
    try:
        manifest = json.loads(raw.decode("utf-8", errors="replace"))
    except ValueError:
        return ""
    head = manifest.get("head") if isinstance(manifest, dict) else None
    return head if isinstance(head, str) and re.fullmatch(r"[0-9a-f]{7,64}", head) else ""


def _raw_starts_within_repo(raw_dir: str, repo_root: Optional[str]) -> bool:
    """True when `raw_dir` is relative or lexically begins under `repo_root`."""
    if not repo_root:
        return False
    raw_s = str(raw_dir)
    if not os.path.isabs(raw_s):
        return True
    for base in (str(repo_root), os.path.abspath(repo_root), os.path.realpath(repo_root)):
        prefix = base.rstrip(os.sep) + os.sep
        if raw_s == base.rstrip(os.sep) or raw_s.startswith(prefix):
            return True
    return False


def _validate_knowledge_dir(target_dir: str, repo_root: Optional[str], *, create: bool,
                            err_cls: type[Exception]) -> Path:
    """Validates `target_dir` against symlink traversal and repo escape.

    Refuses symlinks on `target_dir`, on any intermediate directory under
    `repo_root` (when `target_dir` targets the repository), and on any entry
    already present inside `target_dir`. Also refuses paths inside `.git`.
    """
    raw_s = str(target_dir or "").strip()
    if not raw_s:
        raise err_cls("knowledge directory path is empty")

    in_repo = _raw_starts_within_repo(raw_s, repo_root)
    if in_repo and repo_root:
        repo_real = Path(os.path.realpath(repo_root))
        if os.path.isabs(raw_s):
            # Preserve lexical `..` segments relative to whichever repo spelling matched.
            matched_base = next(
                b.rstrip(os.sep)
                for b in (str(repo_root), os.path.abspath(repo_root), str(repo_real))
                if raw_s == b.rstrip(os.sep) or raw_s.startswith(b.rstrip(os.sep) + os.sep)
            )
            rel_raw = raw_s[len(matched_base):].lstrip(os.sep)
        else:
            rel_raw = raw_s
        parts = [p for p in rel_raw.replace("\\", "/").split("/") if p and p != "."]
        if any(p == ".." for p in parts):
            raise err_cls(f"refusing parent traversal in knowledge directory '{target_dir}'")
        if ".git" in parts:
            raise err_cls(f"refusing knowledge directory inside .git: '{target_dir}'")
        cur = repo_real
        for part in parts:
            cur = cur / part
            if os.path.lexists(cur):
                st = os.lstat(cur)
                if stat.S_ISLNK(st.st_mode):
                    raise err_cls(f"refusing symlink component '{cur}' along knowledge directory")
                if not stat.S_ISDIR(st.st_mode):
                    raise err_cls(f"knowledge directory component '{cur}' is not a directory")
            elif create:
                cur.mkdir(mode=0o755, exist_ok=False)
            else:
                raise err_cls(f"{target_dir} is not a directory")
        resolved = Path(os.path.realpath(cur))
        try:
            rel_resolved = resolved.relative_to(repo_real)
        except ValueError as exc:
            raise err_cls(f"knowledge directory '{target_dir}' resolves outside repository '{repo_real}'") from exc
        if ".git" in rel_resolved.parts:
            raise err_cls(f"refusing knowledge directory inside .git: '{target_dir}'")
        out = cur
    else:
        raw_path = Path(raw_s)
        if os.path.islink(raw_path):
            raise err_cls(f"refusing symlinked knowledge directory '{target_dir}'")
        abs_path = Path(os.path.abspath(raw_s))
        if ".git" in abs_path.parts:
            raise err_cls(f"refusing knowledge directory inside .git: '{target_dir}'")
        # Walk from the deepest existing ancestor so newly created segments and
        # the leaf directory are verified with lstat (without tripping on OS root
        # aliases such as /var -> /private/var).
        missing: List[str] = []
        probe = abs_path
        while not os.path.lexists(probe):
            missing.append(probe.name)
            if probe.parent == probe:
                break
            probe = probe.parent
        if os.path.lexists(probe):
            st = os.lstat(probe)
            if stat.S_ISLNK(st.st_mode):
                raise err_cls(f"refusing symlink component '{probe}' along knowledge directory")
            if not stat.S_ISDIR(st.st_mode):
                raise err_cls(f"{target_dir} is not a directory")
        if missing and not create:
            raise err_cls(f"{target_dir} is not a directory")
        cur = Path(os.path.realpath(probe))
        for part in reversed(missing):
            cur = cur / part
            cur.mkdir(mode=0o755, exist_ok=False)
        out = cur

    with os.scandir(out) as it:
        for entry in it:
            if entry.is_symlink():
                raise err_cls(f"refusing symlink '{entry.name}' inside knowledge directory '{target_dir}'")
    return out


def _atomic_write_text(out: Path, name: str, text: str) -> None:
    """Writes `out / name` via a sibling temp file + os.replace without following symlinks."""
    if not name or Path(name).name != name or name in (".", ".."):
        raise PermissionError(f"invalid knowledge filename '{name}'")
    if os.path.islink(out):
        raise PermissionError(f"refusing symlinked knowledge directory '{out}'")
    dst = out / name
    if os.path.lexists(dst):
        st = os.lstat(dst)
        if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
            raise PermissionError(f"refusing to overwrite non-regular file or symlink '{dst}'")
        if st.st_nlink > 1:
            raise PermissionError(f"refusing to overwrite hard-linked file '{dst}'")
    fd, tmp_path = tempfile.mkstemp(dir=str(out), prefix=f".{name}.", suffix=".tmp")
    try:
        data = text.encode("utf-8")
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        if os.path.lexists(dst):
            st = os.lstat(dst)
            if stat.S_ISLNK(st.st_mode) or not stat.S_ISREG(st.st_mode):
                raise PermissionError(f"refusing to overwrite non-regular file or symlink '{dst}'")
        os.replace(tmp_path, dst)
    except BaseException:
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
        raise


def export_knowledge(db_path: str, out_dir: str, repo_root: Optional[str] = None,
                     head: Optional[str] = None) -> Dict[str, Any]:
    """Writes the knowledge base under `out_dir` as text. Returns counts.

    `repo_root` is the directory finding paths are relative to and the root
    coverage paths are made relative to; anything outside it is left out.
    `head` is the commit the knowledge reflects (defaults to the checkout's
    HEAD); an incremental refresh uses it as the base of its next diff. The
    output is deterministic for a given database and head: the same rows
    produce the same bytes, so a re-export after a run diffs to exactly what
    changed.
    """
    out = _validate_knowledge_dir(out_dir, repo_root, create=True, err_cls=PermissionError)
    conn = _connect(db_path)
    try:
        findings = _export_findings(conn, repo_root)
        learnings = _export_learnings(conn)
        tm_json = _latest_artifact(conn, artifact_type=_ART_THREAT_MODEL[0])
        tm_md = _latest_artifact(conn, filepaths=("workspace/kb/THREAT_MODEL.md", "workspace/kb/threat_model.md"))
        arch_md = _latest_artifact(conn, filepaths=(_ART_ARCHITECTURE[1],))
        summary_json = _latest_artifact(conn, artifact_type=_ART_SUMMARY[0])
        coverage = _export_coverage(conn, repo_root)
        runs = _export_runs(conn)
    finally:
        conn.close()

    def write(name: str, text: str) -> None:
        _atomic_write_text(out, name, text)

    def pretty_json(raw: Optional[str]) -> Optional[str]:
        if raw is None:
            return None
        try:
            return json.dumps(json.loads(raw), indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        except ValueError:
            return None

    models = sorted({r["model"] for r in runs if r.get("model")})
    counts = {"findings": len(findings), "learnings": len(learnings),
              "threat_model": bool(tm_json or tm_md), "architecture": bool(arch_md),
              "summary": bool(summary_json), "coverage_runs": len(coverage["runs"]),
              "coverage_paths": len(coverage["scanned"]), "runs": len(runs), "models": models}
    write(FINDINGS, "".join(_json_line(f) + "\n" for f in findings))
    write(LEARNINGS, "".join(_json_line(x) + "\n" for x in learnings))
    write(RUNS, "".join(_json_line(r) + "\n" for r in runs))
    for name, text in ((THREAT_MODEL_JSON, pretty_json(_scrub(tm_json, 10**7) if tm_json else None)),
                       (THREAT_MODEL_MD, _scrub_markdown(tm_md, 10**6) if tm_md else None),
                       (ARCHITECTURE_MD, _scrub_markdown(arch_md, 10**6) if arch_md else None),
                       (SUMMARY_JSON, pretty_json(_scrub(summary_json, 10**7) if summary_json else None))):
        if text:
            write(name, text if text.endswith("\n") else text + "\n")
        elif os.path.lexists(out / name):
            if os.path.islink(out / name):
                raise PermissionError(f"refusing to unlink symlink '{out / name}'")
            (out / name).unlink()
    write(COVERAGE, json.dumps(coverage, indent=2, sort_keys=True, ensure_ascii=False) + "\n")
    write(README, README_TEXT)
    digest = hashlib.sha256()
    for name in (FINDINGS, LEARNINGS, THREAT_MODEL_JSON, THREAT_MODEL_MD, ARCHITECTURE_MD, SUMMARY_JSON, COVERAGE, RUNS):
        p = out / name
        raw_bytes = _read_bounded(p, MAX_FILE_BYTES)
        if raw_bytes is not None:
            digest.update(name.encode())
            digest.update(raw_bytes)
    manifest = {"schema_version": SCHEMA_VERSION, "generator": "mantis", "counts": counts,
                "models": models, "content_sha256": digest.hexdigest()}
    head = head if head is not None else _git_head(repo_root)
    if head:
        manifest["head"] = head
        counts["head"] = head
    write(MANIFEST, json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return counts


