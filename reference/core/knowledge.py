class KnowledgeImportError(Exception):
    """The directory is not a knowledge export this version can read."""


def _read_bounded(path: Path, limit: int = MAX_FILE_BYTES) -> Optional[bytes]:
    try:
        st = os.stat(path, follow_symlinks=False)
    except OSError:
        return None
    if not os.path.isfile(path) or os.path.islink(path) or st.st_size > limit:
        return None
    with open(path, "rb") as fh:
        return fh.read(limit + 1)[:limit]


def _iter_jsonl(path: Path) -> Iterable[Dict[str, Any]]:
    raw = _read_bounded(path)
    if raw is None:
        return
    for line in raw.splitlines():
        if not line.strip() or len(line) > MAX_LINE_BYTES:
            continue
        try:
            obj = json.loads(line.decode("utf-8", errors="replace"))
        except ValueError:
            continue
        if isinstance(obj, dict):
            yield obj


def _short(value: Any) -> str:
    return _scrub(value, MAX_SHORT_CHARS) if isinstance(value, (str, int, float)) and not isinstance(value, bool) else ""


def _number(value: Any) -> Optional[float]:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value) if value == value and abs(value) < 1e12 else None  # no NaN/inf


def _import_findings(conn: sqlite3.Connection, path: Path) -> Tuple[int, int]:
    """Inserts findings the database has not seen: a lineage (or signature)
    already present is left alone, since the database's row is at least as
    current as the export's. Returns (inserted, skipped)."""
    inserted = skipped = 0
    for rec in _iter_jsonl(path):
        filepath = _clean_rel_path(rec.get("filepath"))
        title = _scrub(rec.get("title"), MAX_SHORT_CHARS)
        status = str(rec.get("status") or "").strip().lower()
        if not filepath or not title or not _STATUS_RE.match(status):
            skipped += 1
            continue
        lineage = _short(rec.get("lineage_id"))
        signature = _short(rec.get("signature"))
        if lineage and not _IDENT_RE.match(lineage):
            lineage = ""
        try:
            if lineage and conn.execute("SELECT 1 FROM findings WHERE lineage_id = ? LIMIT 1", (lineage,)).fetchone():
                skipped += 1
                continue
            if signature and conn.execute("SELECT 1 FROM findings WHERE signature = ? LIMIT 1", (signature,)).fetchone():
                skipped += 1
                continue
            lines = [int(x) for x in _parse_list(rec.get("line_numbers"))
                     if isinstance(x, int) and not isinstance(x, bool) and 0 < x < 10**7]
            code_paths = [_clean_rel_path(x) or _scrub(x, MAX_SHORT_CHARS)
                          for x in _parse_list(rec.get("code_paths")) if isinstance(x, str)]
            from core.schemas import normalize_mantis_risk_score
            conn.execute(
                """INSERT OR IGNORE INTO findings
                   (run_id, filepath, title, severity, description, line_numbers, remediation,
                    status, mantis_risk_score, impact_score, likelihood_score, priority,
                    signature, lineage_id, cwe, triage_reasoning, patch_status, rca_summary, code_paths)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
                (_short(rec.get("run_id")) or "imported", filepath, title,
                 _short(rec.get("severity")), _scrub(rec.get("description")), json.dumps(lines),
                 _scrub(rec.get("remediation")), status,
                 normalize_mantis_risk_score(_number(rec.get("mantis_risk_score")), min_score=0.0),
                 _number(rec.get("impact_score")), _number(rec.get("likelihood_score")),
                 _short(rec.get("priority")), signature or None, lineage or None,
                 _short(rec.get("cwe")), _scrub(rec.get("triage_reasoning")),
                 _short(rec.get("patch_status")), _scrub(rec.get("rca_summary")), json.dumps(code_paths)))
            inserted += 1
        except sqlite3.Error:
            skipped += 1
    return inserted, skipped


def _import_learnings(conn: sqlite3.Connection, path: Path) -> int:
    n = 0
    for rec in _iter_jsonl(path):
        text = _scrub(rec.get("learning"))
        cat = _short(rec.get("category"))
        if not text:
            continue
        run_id = _short(rec.get("run_id")) or "imported"
        try:
            if conn.execute("SELECT 1 FROM learnings WHERE category = ? AND learning = ? LIMIT 1",
                            (cat, text)).fetchone():
                continue
            tags = [_scrub(t, MAX_SHORT_CHARS) for t in _parse_list(rec.get("tags")) if isinstance(t, str)]
            conn.execute("INSERT INTO learnings (run_id, category, learning, tags) VALUES (?,?,?,?)",
                         (run_id, cat, text, json.dumps(tags)))
            n += 1
        except sqlite3.Error:
            continue
    return n


def _import_artifact(db_path: str, run_id: str, path: Path, artifact_type: str,
                     dest: str, as_json: bool) -> bool:
    from core.database import record_artifact

    raw = _read_bounded(path, 10**7)
    if raw is None:
        return False
    text = _scrub(raw.decode("utf-8", errors="replace"), 10**7)
    if as_json:
        try:
            text = json.dumps(json.loads(text), sort_keys=True)
        except ValueError:
            return False
    if not text.strip():
        return False
    # An import is text from a repository: the trust tier is what this
    # process knows about it, not what the file's own frontmatter claims.
    # Without the explicit tier, the OKF parser would take `verified: human`
    # from the document and index attacker-writable prose as human-reviewed
    # guidance for every later run.
    record_artifact(db_path, run_id, artifact_type, dest, text,
                    metadata={"imported": True, "trust_tier": "unverified"})
    return True


def _import_runs(db_path: str, runs_path: Path, *record_paths: Path) -> int:
    """Rebuilds the runs table (run id -> model) from the export: runs.jsonl
    when present, else whatever the records themselves say (a v2 export
    without the file, or one edited by hand). A v1 export says nothing and
    its runs stay of unknown model. Returns the number recorded."""
    from core.database import record_run

    pairs: Dict[str, str] = {}
    if runs_path.exists():
        for rec in _iter_jsonl(runs_path):
            run_id = _short(rec.get("run_id"))
            if run_id and _IDENT_RE.match(run_id):
                pairs.setdefault(run_id, _short(rec.get("model")))
    for path in record_paths:
        if not path.exists():
            continue
        if path.suffix == ".jsonl":
            for rec in _iter_jsonl(path):
                run_id, model = _short(rec.get("run_id")), _short(rec.get("model"))
                if run_id and model and _IDENT_RE.match(run_id):
                    pairs.setdefault(run_id, model)
        else:
            raw = _read_bounded(path)
            try:
                data = json.loads(raw.decode("utf-8", errors="replace")) if raw else {}
            except ValueError:
                data = {}
            if isinstance(data, dict):
                for entry in list(data.get("runs") or []) + list(data.get("scanned") or []):
                    if not isinstance(entry, dict):
                        continue
                    run_id = _short(entry.get("run_id") or entry.get("last_run_id"))
                    model = _short(entry.get("model"))
                    if run_id and model and _IDENT_RE.match(run_id):
                        pairs.setdefault(run_id, model)
    n = 0
    for run_id, model in pairs.items():
        if record_run(db_path, run_id, model, metadata={"imported": True}):
            n += 1
    return n


def _import_coverage(db_path: str, path: Path, repo_root: str, targets: List[str]) -> Tuple[int, int]:
    """Replays the coverage ledger under each target the next run may use, and
    stamps every scanned path as covered in the spend ledger (zero tokens, so
    it never counts as a cost observation). Returns (runs, paths)."""
    from core.cost import record_spend
    from core.memory import load_coverage, record_coverage

    raw = _read_bounded(path)
    if raw is None:
        return 0, 0
    try:
        data = json.loads(raw.decode("utf-8", errors="replace"))
    except ValueError:
        return 0, 0
    if not isinstance(data, dict):
        return 0, 0
    root = os.path.realpath(repo_root)
    # What each target's ledger already holds, so replaying the same export
    # twice (every per-file scan of a pull request imports it) adds nothing.
    present: Dict[str, set] = {}
    for target in targets:
        try:
            present[target] = {(str(r.get("run_id") or ""), tuple(sorted(r.get("examined") or [])))
                               for r in (load_coverage(db_path, target).get("runs") or [])
                               if isinstance(r, dict)}
        except Exception:
            present[target] = set()
    runs = 0
    for entry in (data.get("runs") or [])[:1000]:
        if not isinstance(entry, dict):
            continue
        examined = []
        for p in (entry.get("examined") or [])[:100_000]:
            rel = _clean_rel_path(p) if p != "." else "."
            if rel:
                examined.append(root if rel == "." else os.path.join(root, rel))
        if not examined:
            continue
        run_id = _short(entry.get("run_id")) or "imported"
        key = (run_id, tuple(sorted(set(examined))))
        for target in targets:
            if key in present[target]:
                continue
            record_coverage(db_path, run_id, target, examined, snapshot_id=_short(entry.get("snapshot_id")))
            present[target].add(key)
        runs += 1
    paths = 0
    # One row per (path, run): a path two models covered has two rows, each
    # under the run -- and so the model -- that covered it.
    already: set = set()
    try:
        conn = _connect(db_path)
        try:
            already = {(r[0], str(r[1] or "")) for r in conn.execute(
                "SELECT DISTINCT target, run_id FROM campaign_spend WHERE target IS NOT NULL").fetchall()}
        finally:
            conn.close()
    except sqlite3.Error:
        already = set()
    for entry in (data.get("scanned") or [])[:100_000]:
        if not isinstance(entry, dict):
            continue
        rel = _clean_rel_path(entry.get("path")) if entry.get("path") != "." else "."
        if not rel:
            continue
        abs_path = root if rel == "." else os.path.join(root, rel)
        run_id = _short(entry.get("last_run_id")) or "imported"
        if (abs_path, run_id) in already:
            paths += 1
            continue
        # The harness that covered it, carried through so an imported row
        # answers "covered by THIS harness?" the same way a native one does.
        # Bounded to the shape the exporter writes; anything else -- and an
        # export that predates the field -- imports as unknown, which covers
        # for every harness (INV-6).
        fingerprint = _short(entry.get("harness_fingerprint"))
        if not _FINGERPRINT_RE.match(fingerprint):
            fingerprint = ""
        if record_spend(db_path, run_id, abs_path,
                        _short(entry.get("scan_mode")) or "whole", tokens=0,
                        metadata={"imported": True}, harness_fingerprint=fingerprint):
            already.add((abs_path, run_id))
            paths += 1
    # The content each file was covered as. Bounded to the exporter's shape;
    # an entry without a well-formed hash imports as nothing, which leaves
    # the file covered as it was (INV-6). No mtime: the importer's files are
    # a different checkout, and the first probe hashes them once.
    try:
        from core.cost import CONTENT_HASH_CHARS, record_coverage_files

        have: set = set()
        try:
            conn = _connect(db_path)
            try:
                have = {(r[0], str(r[1] or ""), str(r[2] or "")) for r in conn.execute(
                    "SELECT path, run_id, content_hash FROM coverage_files").fetchall()}
            finally:
                conn.close()
        except sqlite3.Error:
            have = set()
        by_run: Dict[str, list] = {}
        for entry in (data.get("files") or [])[:100_000]:
            if not isinstance(entry, dict):
                continue
            rel = _clean_rel_path(entry.get("path"))
            digest = _short(entry.get("content_hash")).lower()
            if not rel or not re.match(r"^[0-9a-f]{%d}$" % CONTENT_HASH_CHARS, digest):
                continue
            run_id = _short(entry.get("run_id")) or "imported"
            abs_path = os.path.join(root, rel)
            if (abs_path, run_id, digest) in have:
                continue
            size = entry.get("size")
            by_run.setdefault(run_id, []).append(
                (abs_path, digest, int(size) if isinstance(size, int) and size >= 0 else None, None))
        for run_id, rows in by_run.items():
            record_coverage_files(db_path, run_id, root, rows)
    except Exception:
        pass
    return runs, paths


def import_knowledge(db_path: str, in_dir: str, run_id: str, repo_root: str,
                     target: Optional[str] = None) -> Dict[str, Any]:
    """Reads a knowledge export into the database. Returns counts.

    Findings and learnings are added as history (the run ids they carry are
    kept); the threat model, architecture, and summary are recorded under
    `run_id` so the run's own tools find them; coverage is replayed for
    `repo_root` and, if different, `target`. Raises KnowledgeImportError when
    the directory is not an export this version reads; everything else
    degrades to "that part was not imported".
    """
    src = _validate_knowledge_dir(in_dir, repo_root, create=False, err_cls=KnowledgeImportError)
    raw = _read_bounded(src / MANIFEST, 1 << 20)
    if raw is None:
        raise KnowledgeImportError(f"{in_dir} has no readable {MANIFEST}")
    try:
        manifest = json.loads(raw.decode("utf-8", errors="replace"))
    except ValueError:
        raise KnowledgeImportError(f"{MANIFEST} is not JSON")
    version = manifest.get("schema_version") if isinstance(manifest, dict) else None
    if version not in READABLE_SCHEMA_VERSIONS:
        raise KnowledgeImportError(
            f"knowledge schema_version {version!r} is not one of {READABLE_SCHEMA_VERSIONS}; refusing to guess")

    from core.database import init_db

    init_db(db_path)
    counts: Dict[str, Any] = {}
    counts["runs"] = _import_runs(db_path, src / RUNS, src / FINDINGS, src / LEARNINGS, src / COVERAGE)
    conn = _connect(db_path)
    try:
        with conn:
            counts["findings"], counts["findings_skipped"] = _import_findings(conn, src / FINDINGS)
            counts["learnings"] = _import_learnings(conn, src / LEARNINGS)
    finally:
        conn.close()
    counts["threat_model"] = _import_artifact(db_path, run_id, src / THREAT_MODEL_JSON, *_ART_THREAT_MODEL, as_json=True)
    counts["threat_model_md"] = _import_artifact(db_path, run_id, src / THREAT_MODEL_MD, *_ART_THREAT_MODEL_MD, as_json=False)
    counts["architecture"] = _import_artifact(db_path, run_id, src / ARCHITECTURE_MD, *_ART_ARCHITECTURE, as_json=False)
    counts["summary"] = _import_artifact(db_path, run_id, src / SUMMARY_JSON, *_ART_SUMMARY, as_json=True)
    targets = [str(repo_root)]
    if target and os.path.realpath(str(target)) != os.path.realpath(str(repo_root)):
        targets.append(str(target))
    counts["coverage_runs"], counts["coverage_paths"] = _import_coverage(db_path, src / COVERAGE, str(repo_root), targets)
    return counts


def describe(counts: Dict[str, Any]) -> str:
    """One line for a log: what an import or export carried."""
    parts = [f"{counts.get('findings', 0)} finding(s)", f"{counts.get('learnings', 0)} learning(s)"]
    if counts.get("threat_model") or counts.get("threat_model_md"):
        parts.append("threat model")
    if counts.get("architecture"):
        parts.append("architecture")
    if counts.get("summary"):
        parts.append("summary")
    parts.append(f"coverage for {counts.get('coverage_paths', 0)} path(s)")
    return ", ".join(parts)
